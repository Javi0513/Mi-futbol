# Animación de entrada antes de iniciar sesión (v11.36)
import sys,os;sys.path.insert(0,os.path.dirname(os.path.abspath(__file__)))
from paths import *
import http.server,threading,functools
from playwright.sync_api import sync_playwright
from fake2 import FAKE2
srv=http.server.ThreadingHTTPServer(('127.0.0.1',8872),functools.partial(type('Q',(http.server.SimpleHTTPRequestHandler,),{'log_message':lambda *a:None}),directory=APP));threading.Thread(target=srv.serve_forever,daemon=True).start()
res=[];errs=[]
def check(n,c,x=''):res.append(bool(c));print(('OK   ' if c else 'FALLA'),n,x)
URL='http://127.0.0.1:8872/index.html'
def pagina(ctx,probar=True):
    pg=ctx.new_page();pg.on('pageerror',lambda e:errs.append(str(e)))
    if probar:pg.add_init_script("window.__probarIntro=true")
    pg.route('**/supabase.js',lambda r:r.fulfill(content_type='application/javascript',body=FAKE2))
    return pg
with sync_playwright() as p:
    b=p.chromium.launch()
    ctx=b.new_context(viewport={'width':390,'height':844},service_workers='block',device_scale_factor=2)
    pg=pagina(ctx);pg.goto(URL);pg.wait_for_timeout(300)
    check('al abrir sin sesión sale la animación',pg.locator('#intro').is_visible())
    check('lleva el logo, el nombre y lo que hace la app',pg.locator('#intro .in-mark').count()==1 and 'Directo' in pg.locator('#intro .in-f').text_content() and 'JV32' in pg.locator('#intro .in-t').text_content())
    check('se puede saltar',pg.locator('#intro .in-skip').count()==1)
    pg.screenshot(path=os.path.join(OUT,'intro-1.png'));pg.wait_for_timeout(1000)
    pg.screenshot(path=os.path.join(OUT,'intro-2.png'));pg.wait_for_timeout(900)
    pg.screenshot(path=os.path.join(OUT,'intro-3.png'));pg.wait_for_timeout(1000)
    pg.screenshot(path=os.path.join(OUT,'intro-4.png'))
    pg.wait_for_timeout(1500)
    check('se quita sola en unos segundos y deja el acceso',pg.locator('#intro').count()==0 and pg.locator('#login').is_visible())
    check('no bloquea el scroll después',not pg.evaluate("document.body.classList.contains('intro-on')"))
    pg.reload();pg.wait_for_timeout(500)
    check('no se repite en la misma sesión',pg.locator('#intro').count()==0)
    ctx.close()
    ctx=b.new_context(viewport={'width':390,'height':844},service_workers='block')
    pg=pagina(ctx);pg.goto(URL);pg.wait_for_timeout(500)
    pg.click('#intro');pg.wait_for_timeout(700)
    check('tocando se salta al momento',pg.locator('#intro').count()==0)
    pg.fill('input[name=email]','ana@x.es');pg.fill('input[name=password]','secreto1');pg.click('[data-auth=login]');pg.wait_for_selector('#app:not(.hidden)')
    check('después se entra normal',pg.locator('#app').is_visible())
    ctx.close()
    ctx=b.new_context(viewport={'width':390,'height':844},service_workers='block',reduced_motion='reduce')
    pg=pagina(ctx);pg.goto(URL);pg.wait_for_timeout(1900)
    check('con «reducir movimiento» es muy corta',pg.locator('#intro').count()==0)
    ctx.close()
    ctx=b.new_context(viewport={'width':390,'height':844},service_workers='block')
    pg=pagina(ctx,False);pg.goto(URL);pg.wait_for_timeout(400)
    check('las pruebas automáticas no la ven (no molesta)',pg.locator('#intro').count()==0)
    ctx.close()
    ctx=b.new_context(viewport={'width':1180,'height':820},service_workers='block',device_scale_factor=2)
    pg=pagina(ctx);pg.goto(URL);pg.wait_for_timeout(2700)
    check('en tablet también cabe',pg.evaluate("document.querySelector('.in-t').getBoundingClientRect().right<=innerWidth"))
    pg.screenshot(path=os.path.join(OUT,'intro-tablet.png'))
    ctx.close()
    b.close()
print('PASS' if all(res) and not errs else 'FAIL',sum(res),'/',len(res),errs)
